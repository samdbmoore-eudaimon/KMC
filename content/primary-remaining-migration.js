  for (const [topic, sections] of Object.entries(REPAIRS)) {
    sections.forEach((examples, sectionIndex) => {
      examples.forEach((repair, exampleIndex) => {
        const current = lessons[topic].sections[sectionIndex].examples[exampleIndex];
        if (repair.q) lessons[topic].sections[sectionIndex].examples[exampleIndex] = { ...repair };
        else current.structureId = repair.structureId;
      });
    });
  }
