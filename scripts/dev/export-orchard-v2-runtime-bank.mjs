// Claude (playthrough recovery): writes expeditions/v2/generation/runtime-bank.js, the compact runtime table of the
// 64 certified displaced Four Locks tier 1 entries plus the certified fallback, from Codex's bank manifest.
// node scripts/dev/export-orchard-v2-runtime-bank.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "docs/expeditions/v2/certification/four-locks/displaced-v1/bank-manifest.json"), "utf8"));
if (!manifest.complete || manifest.entries.length !== 64) throw new Error("Bank manifest is not complete");
const row = (e) => ({ layoutId: e.layoutId, parameterSeed: e.parameterSeed, deltas: e.parameters.deltas, sourceTopologyHash: e.parameters.sourceTopologyHash, contentHash: e.contentHash, certificateId: e.certificateId, source: e.source });
const body = `// GENERATED by scripts/dev/export-orchard-v2-runtime-bank.mjs from displaced-v1/bank-manifest.json. Do not edit.
export const RUNTIME_BANK_PACKET = ${JSON.stringify(manifest.packetId)};
export const RUNTIME_BANK = ${JSON.stringify(manifest.entries.map(row), null, 1)};
export const RUNTIME_BANK_FALLBACK = ${JSON.stringify(row(manifest.referenceFallback), null, 1)};
`;
fs.writeFileSync(path.join(root, "expeditions/v2/generation/runtime-bank.js"), body);
console.log("wrote runtime-bank.js:", manifest.entries.length, "entries + fallback");
