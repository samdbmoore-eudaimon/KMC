// Claude: exports the PRIVATE DEVELOPMENT pool used by the main App's Expeditions access (Sam's 5 October instruction).
// node scripts/dev/export-orchard-v2-private-bank.mjs
// Reads every bank-scan result under docs/expeditions/v2/certification/scan/ (later files win for the same
// family/tier/layout/seed), keeps only candidates the real-reducer planner proved winnable (accepted), verifies each one still regenerates
// to the same content hash, and writes expeditions/v2/generation/private-dev-bank.js. These entries are NOT certified: no certificate
// IDs, no historical certificate is touched, Four Locks tier 1 keeps its certified runtime bank.
import fs from "node:fs";
import path from "node:path";
import { registerOrchardPuzzleHooks } from "../../expeditions/v2/puzzles/index.js";
import { generateFourLocksCandidate } from "../../expeditions/v2/generation/four-locks.js";
import { generateTurningRavineCandidate } from "../../expeditions/v2/generation/turning-ravine.js";
import { generateUnequalCrossingCandidate } from "../../expeditions/v2/generation/unequal-crossing.js";
import { generateMaybeFlockCandidate } from "../../expeditions/v2/generation/maybe-flock.js";
import { generateHollowBoughCandidate } from "../../expeditions/v2/generation/hollow-bough.js";
import { hashValue } from "../../expeditions/v2/index.js";

const GENERATORS = { "four-locks": generateFourLocksCandidate, "turning-ravine": generateTurningRavineCandidate, "unequal-crossing": generateUnequalCrossingCandidate, "maybe-flock": generateMaybeFlockCandidate, "hollow-bough": generateHollowBoughCandidate };
const CAP = 64;
const dir = new URL("../../docs/expeditions/v2/certification/scan/", import.meta.url);
registerOrchardPuzzleHooks();

const files = fs.readdirSync(dir).filter((f) => /^[a-z-]+-t\d-s\d+-\d+(-v\d)?\.json$/.test(f)).map((f) => ({ f, t: fs.statSync(new URL(f, dir)).mtimeMs })).sort((a, b) => a.t - b.t);
const byKey = new Map();
for (const { f } of files) {
  const data = JSON.parse(fs.readFileSync(new URL(f, dir), "utf8"));
  const family = data.summary.family, tier = data.summary.tier;
  for (const row of data.rows) {
    const key = `${family}|${tier}|${row.layoutId}|${row.seed}`;
    if (row.accepted) byKey.set(key, { family, tier, layoutId: row.layoutId, seed: row.seed, contentHash: row.contentHash, puzzle: row.puzzle, topology: row.topology, scan: f });
    else byKey.delete(key);
  }
}
const groups = new Map();
for (const e of byKey.values()) { const k = `${e.family}|${e.tier}`; groups.set(k, [...(groups.get(k) || []), e]); }

const out = {}, report = [];
for (const [k, list] of [...groups].sort()) {
  const [family, tier] = k.split("|"), verified = [];
  for (const e of list.sort((a, b) => (a.layoutId < b.layoutId ? -1 : a.layoutId > b.layoutId ? 1 : a.seed - b.seed))) {
    const c = GENERATORS[family]({ tier: Number(tier), seed: e.seed, layoutId: e.layoutId });
    if (c.status === "success" && hashValue(c.blueprint) === e.contentHash) verified.push(e);
  }
  // Round-robin across distinct puzzle patterns first so a capped pool keeps the most variety.
  const byPuzzle = new Map();
  for (const e of verified) byPuzzle.set(e.puzzle, [...(byPuzzle.get(e.puzzle) || []), e]);
  const picked = [];
  for (let round = 0; picked.length < CAP; round += 1) {
    let any = false;
    for (const items of byPuzzle.values()) if (items[round] && picked.length < CAP) { picked.push(items[round]); any = true; }
    if (!any) break;
  }
  if (picked.length) {
    out[`${family}:${tier}`] = picked.map((e) => [e.layoutId, e.seed, e.contentHash]);
    report.push({ family, tier: Number(tier), scannedAccepted: list.length, hashVerified: verified.length, exported: picked.length, distinctPuzzles: new Set(picked.map((e) => e.puzzle)).size, distinctTopologies: new Set(picked.map((e) => e.topology)).size });
  }
}
const body = `// GENERATED by scripts/dev/export-orchard-v2-private-bank.mjs. Do not edit.
// PRIVATE DEVELOPMENT pool: each entry [layoutId, seed, contentHash] was proved winnable by the real-reducer planner (direct plan plus an
// alcove plan plus a second distinct-team plan) but is NOT certified: no certificates, no diversity certification, no device/child testing.
export const PRIVATE_DEV_BANK = ${JSON.stringify(out)};
export const PRIVATE_DEV_BANK_REPORT = ${JSON.stringify(report)};
`;
fs.writeFileSync(path.join("expeditions/v2/generation/private-dev-bank.js"), body);
console.table(report);
